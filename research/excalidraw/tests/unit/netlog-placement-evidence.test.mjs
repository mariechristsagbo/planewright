// Checks the committed placement of the netlog entries (evidence/netlog-steps.json) against the
// committed evidence index (evidence/sessions.json): the same sessions, timeline rows, entries,
// origins, events and drawing steps. Neither file is regenerated here; the raw records stay
// outside the repository.
import { describe, expect, it } from 'vitest';

import { evidence, session } from './r76-evidence.mjs';

const placed = () => evidence('netlog-steps.json');
// Every entry text of a placed session, in placement order.
const texts = (s) => s.placements.flatMap((p) => p.entries).concat(s.before_first_step);
// The origin (or scheme) that an entry text names: its first URL-like word.
const originOf = (text) => /\s((?:https?|wss?):\/\/[^/\s]+|[a-z]+:)(?:\/|\s|$)/u.exec(text)?.[1];
const tally = (items) => {
  const out = {};
  for (const item of items) out[item] = (out[item] ?? 0) + 1;
  return out;
};

describe('the committed netlog placement', () => {
  it('is generated by netlog-steps.mjs for every session of the index, in its order', () => {
    expect(placed().schema).toBe('planewright-research-netlog-steps/v1');
    expect(placed().generated_by).toBe('research/excalidraw/netlog-steps.mjs');
    expect(placed().drawing_steps).toEqual(['drag', 'path', 'touchDrag']);
    expect(placed().sessions.map((s) => s.session)).toEqual(
      evidence('sessions.json').sessions.map((s) => s.session),
    );
  });

  it('places every netlog entry and every timeline row that the index counts', () => {
    for (const s of placed().sessions) {
      const indexed = session(s.session);
      const counted = indexed.network.reduce((sum, e) => sum + e.count, 0);
      expect(s.timeline_rows, s.session).toBe(indexed.steps.total);
      expect(s.netlog_entries, s.session).toBe(counted);
      expect(texts(s), s.session).toHaveLength(counted);
      const lines = s.placements.map((p) => p.line);
      expect(Math.max(...lines), s.session).toBeLessThanOrEqual(s.timeline_rows);
      const starts = s.placements.map((p) => Date.parse(p.started));
      expect(
        starts.every((t, k) => k === 0 || starts[k - 1] <= t),
        s.session,
      ).toBe(true);
    }
  });

  it('names the same origins and events as the index, as often', () => {
    for (const s of placed().sessions) {
      const indexed = session(s.session).network;
      const byOrigin = {};
      const byEvent = {};
      for (const e of indexed) {
        byOrigin[e.origin] = (byOrigin[e.origin] ?? 0) + e.count;
        byEvent[e.event] = (byEvent[e.event] ?? 0) + e.count;
      }
      expect(tally(texts(s).map(originOf)), s.session).toEqual(byOrigin);
      expect(tally(texts(s).map((text) => text.split(' ')[1])), s.session).toEqual(byEvent);
    }
  });

  it('counts the drawing steps that the index counts by kind', () => {
    for (const s of placed().sessions) {
      const { byKind } = session(s.session).steps;
      for (const kind of placed().drawing_steps)
        expect(s.drawing.steps[kind], `${s.session} ${kind}`).toBe(byKind[kind] ?? 0);
    }
  });
});
